// Packs converted Rocketbox avatars (build/people/*.glb plus Deal Room's business cast) into
// AsokaCityPeople* static resources under 5 MB each, copies the standing clips into AsokaCityMoves,
// and writes AsokaCity/peoplelist.js and the pack URLs in the Visualforce page.
//   node tools/pack-people.mjs <deal-room staticresources dir>
import fs from "node:fs"; import path from "node:path"; import url from "node:url";
const root = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const SR = path.join(root, "force-app/main/default/staticresources");
const dr = process.argv[2];
const LICENSE = path.join(dr, "DealRoomCast1/ROCKETBOX-LICENSE.md");
const files = [];
for (const f of fs.readdirSync(path.join(root, "build/people")).sort()) files.push(path.join(root, "build/people", f));
for (const d of ["DealRoomCast1", "DealRoomCast2", "DealRoomCast3", "DealRoomCast4"]) for (const f of fs.readdirSync(path.join(dr, d))) if (f.endsWith(".glb")) files.push(path.join(dr, d, f));
for (const d of fs.readdirSync(SR)) if (/^AsokaCityPeople\d+$/.test(d)) fs.rmSync(path.join(SR, d), { recursive: true, force: true });
for (const d of fs.readdirSync(SR)) if (/^AsokaCityPeople\d+\.resource-meta\.xml$/.test(d)) fs.rmSync(path.join(SR, d));
const LIMIT = 4.6 * 1024 * 1024;
let pack = 1, size = 0;
const list = [];
const meta = (desc) => `<?xml version="1.0" encoding="UTF-8"?>\n<StaticResource xmlns="http://soap.sforce.com/2006/04/metadata">\n    <cacheControl>Private</cacheControl>\n    <contentType>application/zip</contentType>\n    <description>${desc}</description>\n</StaticResource>\n`;
const open = (n) => {
  const dir = path.join(SR, "AsokaCityPeople" + n);
  fs.mkdirSync(dir, { recursive: true });
  fs.copyFileSync(LICENSE, path.join(dir, "ROCKETBOX-LICENSE.md"));
  fs.writeFileSync(path.join(SR, `AsokaCityPeople${n}.resource-meta.xml`), meta(`Asoka City people, pack ${n}: Microsoft Rocketbox avatars (MIT, see ROCKETBOX-LICENSE.md) as GLB.`));
  return dir;
};
let dir = open(pack);
for (const f of files) {
  const s = fs.statSync(f).size;
  if (size + s > LIMIT) { pack++; size = 0; dir = open(pack); }
  fs.copyFileSync(f, path.join(dir, path.basename(f)));
  size += s;
  const id = path.basename(f, ".glb");
  list.push({ id, g: /Female/.test(id) ? "f" : "m", pack: "AsokaCityPeople" + pack, kind: /Business/.test(id) ? "business" : "casual" });
}
const moves = path.join(SR, "AsokaCityMoves");
fs.mkdirSync(moves, { recursive: true });
fs.copyFileSync(LICENSE, path.join(moves, "ROCKETBOX-LICENSE.md"));
for (const c of ["m_idle_neutral", "f_idle_neutral", "m_gestic_listen_neutral", "f_gestic_listen_neutral", "m_cell_phone_talk", "m_gestic_talk_relaxed", "f_gestic_talk_relaxed"]) fs.copyFileSync(path.join(dr, "DealRoomMoves", c + ".json"), path.join(moves, c + ".json"));
fs.writeFileSync(path.join(SR, "AsokaCityMoves.resource-meta.xml"), meta("Asoka City standing motion clips from Microsoft Rocketbox (MIT, see ROCKETBOX-LICENSE.md), as compact JSON."));
fs.writeFileSync(path.join(SR, "AsokaCity/peoplelist.js"), "// Generated by tools/pack-people.mjs: every avatar, its rig family for motion clips (f/m), and its pack.\nexport const PEOPLE = " + JSON.stringify(list) + ";\n");
// Page: pack URLs for cars, people and moves.
const page = path.join(root, "force-app/main/default/pages/AsokaCity.page");
const packs = ["AsokaCityCars", "AsokaCityCars2", "AsokaCityCars3", "AsokaCityCars4", "AsokaCityCars5", ...Array.from({ length: pack }, (_, i) => "AsokaCityPeople" + (i + 1)), "AsokaCityMoves"];
const src = fs.readFileSync(page, "utf8").replace(/window\.AC_RES = [^\n]*\n/, "window.AC_RES = { " + packs.map((p) => `${p}: '{!URLFOR($Resource.${p})}'`).join(", ") + " };\n");
fs.writeFileSync(page, src);
console.log(list.length, "avatars in", pack, "packs");
